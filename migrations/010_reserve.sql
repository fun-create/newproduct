-- NEW PRODUCT 010 — 予備時間（F-5-7 ／ 2026-09-23 十文字さんの決定）。
--
-- **実作業と予備を1つの数に混ぜない。**足して1本にすると、
-- AI削減の試算（予備を外して作られている）と月次の負荷が同じ数字を指さなくなる。
-- 行に `kind` を持たせ、**同じ表に入れたまま、集計で分ける。**
--
-- **量は旧テンプレートの半分・1人分**（十文字さんの言葉「16時間×2人であれば、8時間だけ」）。
-- 旧表は1フローにつき 管理者と メンバーへ同額（名入れなら各16.0h）を置いていた。
-- **それは実作業の合計とほぼ同じ大きさ**で、元の分析も「各フローの大きなバッファ」として
-- 削減試算から除外している。採用値は 役割ごとの値 ÷2 を**1行だけ**。
--
--   名入れ 8.000 ／ フリーカット 9.875 ／ Webdeco 9.375
--   ニューモデル 3.375 ／ 資材リニューアル 8.750 ／ 既成デザイン 5.625
--
-- **端数を丸めない。**19.75 ÷ 2 = 9.875。丸めると「半分」でなくなり、
-- 元の値へ戻せなくなる。
--
-- ⑦ページリニューアルには入れない。**旧表に予備時間の行が無い**（発明しない）。

ALTER TABLE task_template ADD COLUMN kind TEXT NOT NULL DEFAULT '実作業';
ALTER TABLE task          ADD COLUMN kind TEXT NOT NULL DEFAULT '実作業';

CREATE INDEX IF NOT EXISTS idx_task_kind ON task (kind);
