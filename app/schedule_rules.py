def norm(t: str) -> str:
    """名前を比べる形に。空白・「※」から後・「→」から後を落とす（シートの改訂で後ろが変わっていても引ける）。"""
    t = (t or "").replace("　", " ")
    t = re.split(r"\s*※", t)[0]
    t = re.split(r"→", t)[0]
    t = t.replace("・マスタ更新", "")
    return re.sub(r"\s+", "", t)


_ALIAS_N = {norm(k): norm(v) for k, v in ALIASES.items()}


def rule_for(flow: str | None, title: str, common: bool = True) -> tuple[str, str, str] | None:
    """(開始, 期限, 出どころ)。見つからなければ None（**推測で当てない**）。"""
    # 頭にバリエーション名が付いた名前（例「18 DUO 試作・調整」「ネームプレート　ピンの…」）は、空白の後ろでも引く
    raw = (title or "").replace("\u3000", " ").strip()
    parts = raw.split()
    names = [raw] + [" ".join(parts[i:]) for i in range(1, len(parts))]
    for rows in (RULES.get(flow or "", []), COMMON if common else []):   # 開発タイプのルール → 共通の提案、の順
        for cand in names:
            n = norm(cand)
            n = _ALIAS_N.get(n, n)
            for t, s, d, src in rows:               # 1回目は同じ名前だけ
                if norm(t) == n:
                    return s, d, src
            for t, s, d, src in rows:               # 2回目は前方一致（シートの改訂で後ろに足された名前）
                m = norm(t)
                if len(min(m, n, key=len)) >= 6 and (n.startswith(m) or m.startswith(n)):
                    return s, d, src
    return None


def guess_flow(titles: list[str]) -> str | None:
    """開発タイプが空の案件（移行分）で、タスク名がいちばん多く当たるテンプレート。

    共通のタスク（出品など）は数えない。**3件以上・残りの3分の1以上が当たり、2番目より1.5倍以上多いときだけ**決める
    （迷うときは決めない。頭の欄で開発タイプを入れてもらう）。"""
    common = {t for t in titles if rule_for(None, t) is not None}
    rest = [t for t in titles if t not in common]
    scores = sorted(((sum(1 for t in rest if rule_for(flow, t, common=False) is not None), flow) for flow in RULES),
                    reverse=True)
    s1, best = scores[0]
    # 2番目と比べる。**同じ日程になるテンプレート（名入れとフリーカット）は区別しなくてよい**ので比べる相手から外す
    same = lambda f: all(rule_for(f, t, common=False) == rule_for(best, t, common=False) for t in rest)  # noqa: E731
    s2 = max([sc for sc, f in scores[1:] if not same(f)] or [0])
    if rest and s1 >= 3 and s1 * 3 >= len(rest) and s1 >= s2 * 1.5:
        return best
    return None


_STEP = re.compile(r"([+-]\d+|>\d+[md])")


def parse(rule: str) -> list[tuple[str, int]]:
    """'L>2m+4' → [('m', 2), ('a', 4)]。形が違えば ValueError。"""
    if not rule or not rule.startswith("L"):
        raise ValueError(f"計算ルールの形が違います: {rule!r}")
    body, out = rule[1:], []
    pos = 0
    for m in _STEP.finditer(body):
        if m.start() != pos:
            raise ValueError(f"計算ルールの形が違います: {rule!r}")
        x = m.group(1)
        if x[0] == ">":
            out.append(("m" if x[-1] == "m" else "d", int(x[1:-1])))
        else:
            out.append(("a" if x[0] == "+" else "b", int(x[1:])))
        pos = m.end()
    if pos != len(body):
        raise ValueError(f"計算ルールの形が違います: {rule!r}")
    return out


def label(rule: str | None) -> str:
    """画面に出す言葉（例 「発売日の 30 営業日前」）。"""
    if not rule:
        return "ルールなし"
    parts = []
    for op, n in parse(rule):
        parts.append({"b": f"{n}営業日前", "a": f"{n}営業日後",
                      "m": f"{n}か月後以降の最初の営業日", "d": f"{n}日後以降の最初の営業日"}[op])
    return "発売日" + ("" if not parts else "の" + "→".join(parts))
