def end1y(d):
    y, m, dd = map(int, d.split("-"))
    try: e = dt.date(y+1, m, dd)
    except ValueError: e = dt.date(y+1, 2, 28)
    return (e - dt.timedelta(days=1)).isoformat() if not (m == 2 and dd == 29) else e.isoformat()
